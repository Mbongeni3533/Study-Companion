#!/usr/bin/env python3
"""Regenerate the worker modules from the readable sources.

  data/*.json              -> worker/data.js
  page/resources.html      -> worker/page.js
  data/career-path.json    -> worker/career-path-data.js

Run after editing anything under data/ or page/:

    python3 resources-site/scripts/build.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SECTIONS = ["overview", "scholarships", "research", "career", "employment", "library"]


def dump(value: object, indent: int = 0) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2).replace("\n", "\n" + " " * indent)


def build_data() -> None:
    lines = [
        "// Content served by the worker's /api/resources/* routes.",
        "// Generated by resources-site/scripts/build.py from resources-site/data/ -",
        "// edit the JSON there and rerun the script.",
        "",
        "export const resources = {",
    ]
    for name in SECTIONS:
        payload = json.loads((ROOT / "content" / f"{name}.json").read_text(encoding="utf-8"))
        lines.append(f"  {name}: {dump(payload, 2)},")
    lines.append("};")
    lines.append("")
    lines.append("export const library = {")

    documents = json.loads((ROOT / "content" / "library.json").read_text(encoding="utf-8"))
    for document in documents["documents"]:
        text = (ROOT / "content" / "library" / document["file"]).read_text(encoding="utf-8")
        lines.append(f"  {json.dumps(document['slug'])}: {{")
        lines.append(f"    file: {json.dumps(document['file'])},")
        lines.append(f"    content: {json.dumps(text, ensure_ascii=False)},")
        lines.append("  },")
    lines.append("};")
    lines.append("")

    (ROOT / "worker" / "data.js").write_text("\n".join(lines), encoding="utf-8")


def build_page() -> None:
    html = (ROOT / "page" / "resources.html").read_text(encoding="utf-8")
    header = (
        "// The page itself. Generated by resources-site/scripts/build.py from\n"
        "// resources-site/page/resources.html so the worker can serve /resources without\n"
        "// the assets layer rewriting the path.\n\n"
    )
    (ROOT / "worker" / "page.js").write_text(
        header + f"export const pageHtml = {json.dumps(html, ensure_ascii=False)};\n",
        encoding="utf-8",
    )


def build_career_path() -> None:
    payload = json.loads((ROOT / "content" / "career-path.json").read_text(encoding="utf-8"))
    header = (
        "// Career-path dataset for /api/resources/career-path. Generated by\n"
        "// resources-site/scripts/build.py from resources-site/data/career-path.json.\n\n"
    )
    (ROOT / "worker" / "career-path-data.js").write_text(
        header + f"export const careerPath = {dump(payload)};\n", encoding="utf-8"
    )


if __name__ == "__main__":
    build_data()
    build_page()
    build_career_path()
    for name in ("data.js", "page.js", "career-path-data.js"):
        size = (ROOT / "worker" / name).stat().st_size
        print(f"worker/{name} {size:,} bytes")
